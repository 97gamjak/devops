"""Pick release reviewers from generated GitHub release notes."""

from __future__ import annotations

import re

ENTRY = re.compile(
    r"^[*-] .* by @(?P<login>[A-Za-z0-9-]+(?:\[bot\])?) in "
    r"https://github\.com/(?P<repository>[^/]+/[^/]+)/pull/[0-9]+$"
)


def extract_reviewers(notes: str, repository: str) -> list[str]:
    """Return the human PR authors of a repository in release-note order.

    Parameters
    ----------
    notes: str
        Release notes as generated by GitHub.
    repository: str
        The repository as ``owner/name``; PRs of other repositories are skipped.

    Returns
    -------
    list[str]
        Unique logins without bots.

    Examples
    --------
    >>> notes = "* fix: x by @ape33 in https://github.com/o/r/pull/1"
    >>> extract_reviewers(notes, "o/r")
    ['ape33']

    """
    reviewers: list[str] = []
    for line in notes.splitlines():
        match = ENTRY.match(line)
        if not match or match.group("repository") != repository:
            continue
        login = match.group("login")
        if not login.endswith("[bot]") and login not in reviewers:
            reviewers.append(login)
    return reviewers
